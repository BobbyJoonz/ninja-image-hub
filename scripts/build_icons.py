"""Build a local Lucide icon sprite for the dashboard.

The UI must work offline and without a CDN: every icon is vendored into
`frontend/icons/sprite.svg` from the official Lucide package and referenced with
`<svg class="icon"><use href="/static/icons/sprite.svg#lc-NAME"></use></svg>`.

Icons are copied unchanged from the library (no hand-authored artwork). Regenerate with:

    python scripts/build_icons.py
"""
import argparse
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "frontend" / "icons"
VERSION = "1.70.0"
BASE = f"https://cdn.jsdelivr.net/npm/lucide-static@{VERSION}/icons"

# semantic name used in the UI -> icon file name in lucide-static
ICONS = {
    "overview": "layout-dashboard",
    "analytics": "chart-line",
    "operations": "sliders-horizontal",
    "accounts": "users",
    "account": "user-round",
    "studio": "wand-sparkles",
    "jobs": "list-checks",
    "gallery": "images",
    "image": "image",
    "grid": "layout-grid",
    "settings": "settings",
    "mask": "venetian-mask",
    "sparkles": "sparkles",
    "clock": "clock",
    "arrow-up-right": "arrow-up-right",
    "arrow-right": "arrow-right",
    "refresh": "refresh-cw",
    "x": "x",
    "plus": "plus",
    "pencil": "pencil",
    "play": "play",
    "stop": "square",
    "login": "log-in",
    "pause": "pause",
    "logs": "file-text",
    "archive": "archive",
    "restore": "rotate-ccw",
    "trash": "trash-2",
    "download": "download",
    "zip": "file-archive",
    "external": "external-link",
}

SVG_RE = re.compile(r"<svg[^>]*>(?P<body>.*)</svg>", re.DOTALL)
COMMENT_RE = re.compile(r"<!--.*?-->", re.DOTALL)
LICENSE = """Lucide icon set - https://lucide.dev
Version: {version}
License: ISC (https://github.com/lucide-icons/lucide/blob/main/LICENSE)
Files in sprite.svg are copied unchanged from the lucide-static npm package.
Generated by scripts/build_icons.py - do not edit by hand.
"""


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "ninja-image-hub-icon-builder"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read().decode("utf-8")


def build():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    symbols = []
    failures = []
    for key, name in ICONS.items():
        try:
            raw = fetch(f"{BASE}/{name}.svg")
        except Exception as exc:  # noqa: BLE001 - report every failed icon
            failures.append(f"{name}: {exc}")
            continue
        body = COMMENT_RE.sub("", raw)
        match = SVG_RE.search(body)
        if not match:
            failures.append(f"{name}: no <svg> body")
            continue
        inner = " ".join(match.group("body").split())
        symbols.append(
            f'  <symbol id="lc-{key}" viewBox="0 0 24 24">'
            f'<g fill="none" stroke="currentColor" stroke-width="2" '
            f'stroke-linecap="round" stroke-linejoin="round">{inner}</g></symbol>'
        )
    if failures:
        print("failed icons:\n  " + "\n  ".join(failures), file=sys.stderr)
        return 1

    sprite = (
        "<!-- Generated by scripts/build_icons.py - Lucide "
        f"{VERSION} (ISC). Do not edit by hand. -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n'
        + "\n".join(symbols)
        + "\n</svg>\n"
    )
    (OUT_DIR / "sprite.svg").write_text(sprite, encoding="utf-8")
    (OUT_DIR / "LICENSE.txt").write_text(
        LICENSE.format(version=VERSION), encoding="utf-8"
    )
    size = (OUT_DIR / "sprite.svg").stat().st_size
    print(f"wrote {len(symbols)} icons -> {OUT_DIR / 'sprite.svg'} ({size} bytes)")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the sprite exists and has every icon")
    args = parser.parse_args()
    if args.check:
        path = OUT_DIR / "sprite.svg"
        if not path.exists():
            sys.exit("sprite.svg is missing; run python scripts/build_icons.py")
        text = path.read_text(encoding="utf-8")
        missing = [key for key in ICONS if f'id="lc-{key}"' not in text]
        if missing:
            sys.exit("sprite is missing icons: " + ", ".join(missing))
        print(f"sprite OK: {len(ICONS)} icons")
        sys.exit(0)
    sys.exit(build())
